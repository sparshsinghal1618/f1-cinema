// Emit src/data/teams.generated.ts from scripts/out/teams.json (written by
// scripts/fetch-teams.mjs). Values are reproduced verbatim; the only edits are
// display tidy-ups: Ferrari's coordinate markup is dropped from the base string,
// wiki footnote markers are removed from race totals, and spaced parentheses are
// closed up. Run: node scripts/make-teams-module.mjs

import { readFile, writeFile } from 'node:fs/promises';

const SOURCE = new URL('./out/teams.json', import.meta.url);
const TARGET = new URL('../src/data/teams.generated.ts', import.meta.url);

const NAME_OVERRIDES = {
  'Atlassian Williams': 'Williams',
  'Aston Martin Aramco': 'Aston Martin',
};

// Separator-only formatting for infobox base strings that list several sites
// without punctuation between them. The wording is unchanged.
const BASE_OVERRIDES = {
  audi: 'Hinwil, Zurich, Switzerland · Bicester, Oxfordshire, United Kingdom · Neuburg an der Donau, Bavaria, Germany',
  cadillac: 'Fishers, Indiana, U.S. · Concord, North Carolina, U.S. · Warren, Michigan, U.S. · Silverstone, England',
};

const esc = (value) => String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
const tidyMarkers = (value) =>
  value
    .replace(/\s*\[\s*[a-z0-9]{1,2}\s*\]\s*/gi, ' ')
    .replace(/\s+([),.;])/g, '$1')
    .replace(/\s{2,}/g, ' ')
    .trim();
const tidyTitles = (value) => tidyMarkers(value).replace(/\s*\(\s*/g, ' (').replace(/\s*\)\s*$/, ')');
const tidyRaces = (value) => (value ? tidyMarkers(value) : '—');
const tidyBase = (value) =>
  tidyMarkers(value)
    .replace(/\s*\d+°[\s\S]*$/, '')
    .trim()
    .replace(/\)\s+(?=[A-Z])/g, ') · ');
const slug = (value) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

const { fetched, season, teams } = JSON.parse(await readFile(SOURCE, 'utf8'));

const note = [
  `The ${season.slice(0, 4)} grid is reproduced from the entrants table of the English Wikipedia article`,
  `${season}, with base, principal, championship counts, first entry and race totals read from each team's own`,
  `article in October ${season.slice(0, 4)}. Nothing is estimated. Line-ups change through a season, so the`,
  'drivers are shown with the rounds each contested as listed on that date.',
];

const rows = teams.map((team) => {
  const name = NAME_OVERRIDES[team.short] ?? team.short;
  const id = slug(name);
  const drivers = team.drivers
    .map((driver, index) => `      { name: '${esc(driver)}', rounds: '${esc(team.rounds[index] ?? '—')}' },`)
    .join('\n');
  return `  {
    id: '${id}',
    name: '${esc(name)}',
    entrant: '${esc(team.entrant)}',
    constructor: '${esc(team.constructor)}',
    chassis: '${esc(team.chassis)}',
    powerUnit: '${esc(team.powerUnit)}',
    numbers: '${esc(team.numbers.replace(/ /g, ', '))}',
    base: '${esc(BASE_OVERRIDES[id] ?? tidyBase(team.fields.base ?? '—'))}',
    principal: '${esc(tidyMarkers(team.fields.principal ?? '—'))}',
    constructorsTitles: '${esc(tidyTitles(team.fields.constructorsTitles ?? '0'))}',
    driversTitles: '${esc(tidyTitles(team.fields.driversTitles ?? '0'))}',
    firstEntry: '${esc(team.fields.firstEntry ?? '—')}',
    races: '${esc(tidyRaces(team.fields.races))}',
    source: '${esc(team.fields.source)}',
    drivers: [
${drivers}
    ],
  },`;
});

const output = `// Generated by scripts/make-teams-module.mjs — do not edit by hand.
// Source: scripts/out/teams.json, fetched ${fetched} by scripts/fetch-teams.mjs.

export interface TeamDriver {
  name: string;
  rounds: string;
}

export interface F1Team {
  id: string;
  name: string;
  entrant: string;
  constructor: string;
  chassis: string;
  powerUnit: string;
  numbers: string;
  base: string;
  principal: string;
  constructorsTitles: string;
  driversTitles: string;
  firstEntry: string;
  races: string;
  source: string;
  drivers: TeamDriver[];
}

export const GRID_YEAR = ${season.slice(0, 4)};

export const TEAMS_NOTE = '${esc(note.join(' '))}';

export const TEAMS: F1Team[] = [
${rows.join('\n')}
];
`;

await writeFile(TARGET, output);
console.log(`teams=${teams.length} -> src/data/teams.generated.ts`);
