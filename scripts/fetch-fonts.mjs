/**
 * Downloads Google Fonts woff2 files locally (latin + latin-ext subsets)
 * and generates src/styles/fonts.css with @font-face rules pointing at
 * public/assets/fonts/*.woff2 — so the site never depends on a CDN.
 */
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import path from 'node:path';
import { existsSync } from 'node:fs';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\//, '').replace(/^(\/([A-Za-z]:))/, '$2')), '..');
const FONT_DIR = path.join(ROOT, 'public', 'assets', 'fonts');
// Emit into public/ so the CSS + woff2 files travel together with relative URLs —
// this keeps @font-face working from any base path (root, subfolder, file://).
const CSS_OUT = path.join(ROOT, 'public', 'assets', 'fonts', 'fonts.css');

// Modern UA => woff2 + unicode-range subsets.
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';

const FAMILIES = [
  'family=Barlow+Condensed:ital,wght@0,600;0,700;0,800;1,700',
  'family=Inter:wght@400;500;600;700',
  'family=JetBrains+Mono:wght@400;500;700',
];

async function main() {
  await mkdir(FONT_DIR, { recursive: true });
  const url = `https://fonts.googleapis.com/css2?${FAMILIES.join('&')}&display=swap`;
  const r = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!r.ok) throw new Error(`css fetch HTTP ${r.status}`);
  const css = await r.text();

  // Keep only latin & latin-ext blocks (the ones we actually need).
  const blocks = css.split('/*').map((b) => '/*' + b);
  const kept = blocks.filter((b) => /^\/\*\s*(latin|latin-ext)\s*\*\//.test(b) && b.includes('@font-face'));

  let out = '/* Generated by scripts/fetch-fonts.mjs - Google Fonts (SIL OFL 1.1). Do not edit by hand. */\n';
  const jobs = [];
  for (const block of kept) {
    const family = block.match(/font-family:\s*'([^']+)'/)?.[1];
    const weight = block.match(/font-weight:\s*(\d+)/)?.[1];
    const style = block.match(/font-style:\s*(\w+)/)?.[1] || 'normal';
    const subset = block.match(/^\/\*\s*([\w-]+)\s*\*\//)?.[1];
    const src = block.match(/url\((https:\/\/[^)]+\.woff2)\)/)?.[1];
    if (!family || !src) continue;
    const slug = `${family.toLowerCase().replace(/\s+/g, '-')}-${weight}-${style}-${subset}.woff2`;
    const dest = path.join(FONT_DIR, slug);
    jobs.push(
      (async () => {
        if (!existsSync(dest)) {
          const fr = await fetch(src, { headers: { 'User-Agent': UA } });
          if (!fr.ok) throw new Error(`woff2 ${fr.status}: ${src}`);
          await writeFile(dest, Buffer.from(await fr.arrayBuffer()));
        }
        const range = block.match(/unicode-range:\s*([^;]+);/)?.[1];
        out += `@font-face {\n  font-family: '${family}';\n  font-style: ${style};\n  font-weight: ${weight};\n  font-display: swap;\n  src: url('./${slug}') format('woff2');${range ? `\n  unicode-range: ${range};` : ''}\n}\n`;
      })()
    );
  }
  await Promise.all(jobs);
  await mkdir(path.dirname(CSS_OUT), { recursive: true });
  await writeFile(CSS_OUT, out);
  console.log(`fonts: ${jobs.length} faces -> src/styles/fonts.css`);
}

main().catch((e) => { console.error('FONT FETCH FAILED:', e.message); process.exit(1); });
